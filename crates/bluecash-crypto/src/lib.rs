/// SHA-256 over the concatenation of `parts`, without allocating a joined buffer.
///
/// Mirrors the variadic `sha256(vararg parts: ByteArray)` in Kotlin's `Bytes.kt`
/// and `sha256(*parts: bytes)` in `server.py`: the parts are fed to the digest in
/// order, so `sha256(&[a, b])` equals `sha256(&[&[a, b].concat()])`.
pub(crate) fn sha256(parts: &[&[u8]]) -> [u8; 32] {
    let mut h = Sha256::new();
    for p in parts {
        h.update(p);
    }
    h.finalize().into()
}

#[cfg(test)]
mod tests {
    use super::sha256;

    #[test]
    fn sha256_matches_known_vectors() {
        // NIST: SHA-256("abc")
        assert_eq!(
            hex::encode(sha256(&[b"abc"])),
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
        );
        // SHA-256("") — the empty input.
        assert_eq!(
            hex::encode(sha256(&[])),
            "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
        );
    }

    #[test]
    fn concatenation_is_equivalent_to_joined_input() {
        assert_eq!(sha256(&[b"foo", b"bar"]), sha256(&[b"foobar"]));
        assert_eq!(sha256(&[b"", b"abc", b""]), sha256(&[b"abc"]));
    }
}
