//! Shared cryptographic core for the BlueCash Protocol.
//!
//! # Compatibility
//!
//! Every function here is byte-compatible with the two existing implementations
//! of the protocol, which are the authoritative reference:
//!
//! * Kotlin — `app/src/main/java/com/bluecash/wallet/core/` (`RsaBlind.kt`, `Merkle.kt`)
//! * Python — `reference-server/server.py`
//!
//! The encodings are fixed by `API_CONTRACT.md`. Changing a domain-separation
//! label, a counter width or a tree-splitting rule here silently breaks
//! interoperability with the Android client, so the tests in `tests/` compare
//! against values generated by the reference server rather than by this crate.
//!
//! # Scope
//!
//! Implemented and tested: the full-domain hash, the RFC 6962 Merkle tree, RSA
//! blind signatures, Ed25519, the Feldman-committed share scheme used for
//! double-spend detection, and the X25519/HKDF/AES-GCM session setup for the
//! BLE channel.
//!
//! Not implemented: the UniFFI layer (PyO3 is present behind the `python`
//! feature), and **BBS+ anonymous credentials**. BBS+ is named as a closed gap
//! in the proposal but exists in neither this crate nor the Android client; it
//! must not be described as supported.

